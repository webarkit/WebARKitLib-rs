/// Verify that a single-page database (db_id = 0) correctly yields a pose.
///
/// This is the core regression test for issue #43: `kpm_matching()` used
/// to skip the pose computation when `matched_id == 0` because the
/// condition was `matched_id > 0` instead of `matched_id >= 0`.
///
/// Additionally, this test exercises the fset3 `KpmImageInfo` field-order
/// fix (width, height, imageNo matching the C++ struct layout).
#[cfg(feature = "ffi-backend")]
#[test]
fn test_matched_db_id_zero_finds_pose() {
    use std::sync::Arc;
    use webarkitlib_rs::kpm::types::KpmRefDataSet;
    use webarkitlib_rs::kpm::{CppFreakMatcher, KpmHandle};
    use webarkitlib_rs::types::{ARParam, ARParamLT};

    // Load camera parameters.
    let cam_path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("benchmarks")
        .join("data")
        .join("camera_para.dat");
    let cam_file = std::fs::File::open(&cam_path).expect("failed to open camera_para.dat");
    let mut cparam =
        ARParam::load(std::io::BufReader::new(cam_file)).expect("failed to load camera_para.dat");

    // Load query image.
    let img_path = data_dir().join("pinball-demo.jpg");
    let jpeg_bytes = std::fs::read(&img_path).expect("failed to read pinball-demo.jpg");
    let mut decoder = jpeg_decoder::Decoder::new(std::io::Cursor::new(&jpeg_bytes));
    let pixels = decoder.decode().expect("JPEG decode failed");
    let info = decoder.info().unwrap();
    let (w, h) = (info.width as i32, info.height as i32);

    let luma: Vec<u8> = pixels
        .chunks_exact(3)
        .map(|rgb| ((rgb[0] as u32 * 77 + rgb[1] as u32 * 150 + rgb[2] as u32 * 29) >> 8) as u8)
        .collect();

    // Resize camera params.
    let sx = w as f64 / cparam.xsize as f64;
    let sy = h as f64 / cparam.ysize as f64;
    for col in 0..4 {
        cparam.mat[0][col] *= sx;
        cparam.mat[1][col] *= sy;
    }
    cparam.xsize = w;
    cparam.ysize = h;
    let cparam_lt = Arc::new(ARParamLT::new_basic(cparam));

    // Load single-page .fset3 — all features will be under db_id = 0..N.
    let fset3_path = data_dir().join("pinball.fset3");
    let mut ref_data_set = KpmRefDataSet::load(&fset3_path).expect("failed to load pinball.fset3");
    assert_eq!(
        ref_data_set.page_num, 1,
        "pinball.fset3 must be single-page"
    );

    // Assign page 0 — this is the scenario that triggered issue #43.
    ref_data_set.change_page_no(
        webarkitlib_rs::kpm::ref_data_set::KPM_CHANGE_PAGE_NO_ALL_PAGES,
        0,
    );

    let backend = CppFreakMatcher::new(w, h).expect("failed to create CppFreakMatcher");
    let mut handle = KpmHandle::new(w, h, Some(cparam_lt), Box::new(backend));
    handle
        .set_ref_data_set(ref_data_set)
        .expect("set_ref_data_set failed");

    // Verify page_ids[0] == 0 (the bug scenario — db_id 0 maps to page 0).
    assert_eq!(handle.page_ids[0], 0, "first db_id should map to page 0");

    handle.kpm_matching(&luma).expect("kpm_matching failed");

    // The core assertion: get_pose() must return Some when db_id == 0.
    let pose_result = handle.get_pose();
    assert!(
        pose_result.is_some(),
        "get_pose() returned None — db_id=0 match was incorrectly skipped"
    );

    let (_pose, page_no, _error) = pose_result.unwrap();
    assert_eq!(page_no, 0, "matched page should be 0");
}
