/// Decode pinball-demo.jpg to RGB, convert to luma using the same BT.601
/// formula as the C++ benchmark, and spot-check pixel values at known
/// locations.
#[test]
fn test_luminance_conversion() {
    let img_path = data_dir().join("pinball-demo.jpg");

    let jpeg_bytes = std::fs::read(&img_path).expect("failed to read pinball-demo.jpg");
    let mut decoder = jpeg_decoder::Decoder::new(std::io::Cursor::new(&jpeg_bytes));
    let pixels = decoder.decode().expect("JPEG decode failed");
    let info = decoder.info().unwrap();
    let w = info.width as usize;
    let h = info.height as usize;

    assert_eq!(w, 2000, "expected width 2000");
    assert_eq!(h, 1500, "expected height 1500");
    assert_eq!(pixels.len(), w * h * 3, "expected RGB pixel data");

    // Convert to luma using BT.601 (same integer formula as C++ stb_image + fixture generator).
    let luma: Vec<u8> = pixels
        .chunks_exact(3)
        .map(|rgb| ((rgb[0] as u32 * 77 + rgb[1] as u32 * 150 + rgb[2] as u32 * 29) >> 8) as u8)
        .collect();

    assert_eq!(luma.len(), w * h);

    // Spot-check: pixels at known locations are accessible.
    let _top_left = luma[0];
    let center = (h / 2) * w + (w / 2);
    let _center_val = luma[center];

    // Verify luma is not constant (real image should have variation).
    let min_luma = *luma.iter().min().unwrap();
    let max_luma = *luma.iter().max().unwrap();
    assert!(
        max_luma - min_luma > 50,
        "luma range too narrow: {min_luma}..{max_luma} — image may not have loaded correctly"
    );

    // Verify the luma histogram is not degenerate (>100 distinct values for a real photo).
    let mut hist = [0u32; 256];
    for &v in &luma {
        hist[v as usize] += 1;
    }
    let distinct = hist.iter().filter(|&&c| c > 0).count();
    assert!(
        distinct > 100,
        "only {distinct} distinct luma values — expected a real photograph"
    );
}

