//! KPM regression tests — numerical validation against C++ baseline.
//!
//! These tests compare Rust outputs to values generated by the C++
//! `kpm_dump_fixtures` tool in `benchmarks/c_benchmark/`. The fixture
//! data (JSON + hardcoded consts) was produced by running the C++ KPM
//! pipeline on `pinball-demo.jpg` and dumping the resulting poses, ICP
//! results, and correspondences.
//!
//! # Test matrix
//!
//! | Test                         | What it validates                              | Feature gate |
//! |------------------------------|------------------------------------------------|--------------|
//! | `test_fset3_load_structure`  | .fset3 binary I/O round-trip                   | none         |
//! | `test_full_pipeline_pose`    | Full kpmMatching pose vs C++ baseline           | ffi-backend  |
//! | `test_standalone_icp`        | ICP refinement on synthetic correspondences     | none         |
//! | `test_luminance_conversion`  | JPEG→luma conversion consistency                | none         |

