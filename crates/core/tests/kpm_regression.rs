// Test 1: .fset3 load structure
// ===========================================================================

/// Validate that `KpmRefDataSet::load` parses pinball.fset3 correctly and
/// produces the exact same structure the C++ code does.
#[test]
fn test_fset3_load_structure() {
    use webarkitlib_rs::kpm::types::KpmRefDataSet;

    let path = data_dir().join("pinball.fset3");

    let ds = KpmRefDataSet::load(&path).expect("failed to load pinball.fset3");

    // From C++ output: 4850 total feature points.
    assert_eq!(ds.num, 4850, "expected 4850 ref points");
    assert_eq!(ds.ref_point.len(), 4850);

    // Single page with 9 pyramid images.
    assert_eq!(ds.page_num, 1, "expected 1 page");
    assert_eq!(ds.page_info.len(), 1);
    assert_eq!(ds.page_info[0].image_num, 9, "expected 9 pyramid images");

    // Feature counts per image match C++ log output.
    // ref_image_no is 0..8 (sequential index into pyramid), not the
    // arbitrary image_no stored in page_info.
    let expected_counts = [636, 648, 615, 607, 590, 540, 508, 437, 269];
    for (i, &expected) in expected_counts.iter().enumerate() {
        let count = ds
            .ref_point
            .iter()
            .filter(|rp| rp.ref_image_no == i as i32)
            .count();
        assert_eq!(
            count, expected,
            "pyramid level {i}: expected {expected} features, got {count}",
        );
    }

    // All features belong to the same page.
    let page_no = ds.page_info[0].page_no;
    assert!(ds.ref_point.iter().all(|rp| rp.page_no == page_no));

    // Descriptors are not all zeros.
    assert!(
        ds.ref_point[0].feature_vec.v.iter().any(|&b| b != 0),
        "first FREAK descriptor should not be all-zero"
    );
}

// ===========================================================================
// Test 2: Full pipeline pose (FFI backend required)
// ===========================================================================

/// Run the full kpmMatching pipeline on pinball-demo.jpg and compare the
/// resulting 3x4 pose matrix to the C++ baseline.
///
/// This test requires the `ffi-backend` feature because it delegates
/// feature extraction to the compiled C++ FreakMatcher library.
///
/// Gated to `target_os = "linux"`: the recorded baseline is
/// platform-specific (see [`EXPECTED_FULL_POSE`] doc comment). CI runs
/// this on Ubuntu; Windows/macOS local runs of `cargo test` will skip
/// it rather than fail on cross-platform rounding divergence.
#[cfg(all(feature = "ffi-backend", target_os = "linux"))]
#[test]
fn test_full_pipeline_pose() {
    use std::sync::Arc;
    use webarkitlib_rs::kpm::types::KpmRefDataSet;
    use webarkitlib_rs::kpm::{CppFreakMatcher, KpmHandle};
    use webarkitlib_rs::types::{ARParam, ARParamLT};

    // Load camera parameters.
    let cam_path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("benchmarks")
        .join("data")
        .join("camera_para.dat");
    let cam_file = std::fs::File::open(&cam_path).expect("failed to open camera_para.dat");
    let mut cparam =
        ARParam::load(std::io::BufReader::new(cam_file)).expect("failed to load camera_para.dat");

    // Load query image (JPEG → RGB → luma).
    let img_path = data_dir().join("pinball-demo.jpg");
    let jpeg_bytes = std::fs::read(&img_path).expect("failed to read pinball-demo.jpg");
    let mut decoder = jpeg_decoder::Decoder::new(std::io::Cursor::new(&jpeg_bytes));
    let pixels = decoder.decode().expect("JPEG decode failed");
    let info = decoder.info().unwrap();
    let (w, h) = (info.width as i32, info.height as i32);
    assert_eq!(w, 2000);
    assert_eq!(h, 1500);

    // Convert RGB → luma (BT.601).
    let luma: Vec<u8> = pixels
        .chunks_exact(3)
        .map(|rgb| ((rgb[0] as u32 * 77 + rgb[1] as u32 * 150 + rgb[2] as u32 * 29) >> 8) as u8)
        .collect();
    assert_eq!(luma.len(), (w * h) as usize);

    // Resize camera params to match image (arParamChangeSize equivalent).
    // Row 0 *= x_scale, Row 1 *= y_scale, Row 2 unchanged.
    let sx = w as f64 / cparam.xsize as f64;
    let sy = h as f64 / cparam.ysize as f64;
    for col in 0..4 {
        cparam.mat[0][col] *= sx;
        cparam.mat[1][col] *= sy;
    }
    cparam.xsize = w;
    cparam.ysize = h;

    let cparam_lt = Arc::new(ARParamLT::new_basic(cparam));

    // Load .fset3 reference data.
    let fset3_path = data_dir().join("pinball.fset3");
    let mut ref_data_set = KpmRefDataSet::load(&fset3_path).expect("failed to load pinball.fset3");

    // Change all pages to page 0 (matches C++ setup).
    ref_data_set.change_page_no(
        webarkitlib_rs::kpm::ref_data_set::KPM_CHANGE_PAGE_NO_ALL_PAGES,
        0,
    );

    // Create KPM handle with C++ backend.
    let backend = CppFreakMatcher::new(w, h).expect("failed to create CppFreakMatcher");
    let mut handle = KpmHandle::new(w, h, Some(cparam_lt), Box::new(backend));
    handle
        .set_ref_data_set(ref_data_set)
        .expect("set_ref_data_set failed");

    // Run matching.
    handle.kpm_matching(&luma).expect("kpm_matching failed");

    // Extract best pose.
    let (pose, page_no, error) = handle
        .get_pose()
        .expect("kpm_matching should find a valid pose for pinball-demo.jpg");

    assert_eq!(page_no, 0, "matched page should be 0");

    // TEMP: capture block for regenerating EXPECTED_FULL_POSE +
    // EXPECTED_FULL_ERROR after the webarkit/WebARKitLib#39 C++ fix
    // converges Linux matched_id with the canonical Windows value.
    // Remove this block once the constants below are updated.
    // (Uses println! intentionally so cargo test --nocapture surfaces
    //  the values without needing a logger.)
    println!("REGEN_BEGIN");
    println!("EXPECTED_FULL_POSE = [");
    for row in pose.iter() {
        print!("    [");
        for (i, v) in row.iter().enumerate() {
            if i > 0 {
                print!(", ");
            }
            print!("{v:e}");
        }
        println!("],");
    }
    println!("];");
    println!("EXPECTED_FULL_ERROR = {error:e};");
    println!("REGEN_END");

    // Compare pose to C++ baseline (tolerance: 1e-2 for full pipeline).
    // See `EXPECTED_FULL_POSE` doc comment for the regeneration recipe.
    assert_pose_near("full_pipeline", pose, &EXPECTED_FULL_POSE, 1e-2);

    // Error should be in the same ballpark.
    let error_diff = (error - EXPECTED_FULL_ERROR).abs();
    assert!(
        error_diff < 2.0,
        "full pipeline error differs by {error_diff:.4} \
         (actual={error:.4}, expected={EXPECTED_FULL_ERROR:.4})",
    );
}

